## 5. Market vs. Supermarket Culture

### At the Market (Pijaca):

**Characteristics:**
- Fresh produce directly from farmers
- Prices sometimes negotiable (especially for large quantities)
- Sold by weight (per kilogram)
- More personal interaction with vendors
- Cash only (usually)
- Open mornings, closed afternoons

**Typical Interaction:**
Vendors are friendly and may offer you a taste (probaj - try it!). It\'s common to chat briefly while shopping.

### At the Supermarket (Supermarket):

**Characteristics:**
- Fixed prices
- Self-service
- Pre-packaged goods
- Less personal interaction
- Card payment accepted
- Open all day

**Cultural Note:** Many Serbians prefer markets for fresh produce (especially fruits and vegetables) but use supermarkets for packaged goods, dairy, and meat.

