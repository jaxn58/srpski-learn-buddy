## 6. Example Conversations

### Conversation 1: At the Fruit Stand

**You:** Dobar dan! Koliko koštaju jabuke?  
**Vendor:** Jabuke su 150 dinara po kilu.  
**You:** Dajte mi dva kila, molim.  
**Vendor:** Izvol\'te. Još nešto?  
**You:** Da, koliko su banane?  
**Vendor:** Banane su 200 dinara.  
**You:** Dajte mi kilo banana.  
**Vendor:** To je 550 dinara, molim.  
**You:** Izvol\'te. Hvala!  
**Vendor:** Molim. Doviđenja!

**Translation:**
- Good day! How much are the apples?
- Apples are 150 dinars per kilo.
- Give me two kilos, please.
- Here you are. Anything else?
- Yes, how much are the bananas?
- Bananas are 200 dinars.
- Give me a kilo of bananas.
- That\'s 550 dinars, please.
- Here you are. Thank you!
- You\'re welcome. Goodbye!

