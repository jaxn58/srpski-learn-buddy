## 3. Quantities & Measurements

### Common Quantities:

| Serbian | English | Example |
|---------|---------|---------|
| kilogram (kilo) | kilogram | **jedan kilo jabuka** (one kilo of apples) |
| pola kila | half a kilo | **pola kila sira** (half a kilo of cheese) |
| gram | gram | **200 grama šunke** (200 grams of ham) |
| litar | liter | **dva litra mleka** (two liters of milk) |
| komad | piece | **tri komada hleba** (three pieces of bread) |
| kesica | bag | **jedna kesica brašna** (one bag of flour) |
| kutija | box | **dve kutije jaja** (two boxes of eggs) |
| pakovanje | package | **jedno pakovanje testenine** (one package of pasta) |
| flaša | bottle | **jedna flaša ulja** (one bottle of oil) |

### Number Agreement with Nouns:

Serbian nouns change form depending on the number:

**With 1:** Nominative singular
- **jedan paradajz** (one tomato)
- **jedna jabuka** (one apple)
- **jedno jaje** (one egg)

**With 2, 3, 4:** Genitive singular
- **dva paradajza** (two tomatoes)
- **tri jabuke** (three apples)
- **četiri jajeta** (four eggs)

**With 5+:** Genitive plural
- **pet paradajza** (five tomatoes)
- **deset jabuka** (ten apples)
- **dvadeset jaja** (twenty eggs)

