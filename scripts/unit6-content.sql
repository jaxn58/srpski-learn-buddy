**Vendor:** Evo mleka. Još nešto?  
**You:** Ne, hvala. To je sve. Koliko je?  
**Vendor:** To je 320 dinara.  
**You:** Izvol\'te.  
**Vendor:** Hvala. Dobar dan!

**Translation:**
- Excuse me, do you have fresh cheese?
