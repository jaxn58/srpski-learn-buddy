## 💡 Cultural Tips

1. **Cash is King:** Markets usually only accept cash (dinars). Have small bills ready.

2. **Morning Shopping:** Markets are busiest in the morning (7-11 AM) when produce is freshest.

3. **Taste Before Buying:** Vendors often offer samples. It\'s polite to accept!

4. **Bring Your Bag:** Bring a reusable shopping bag (kesa). Some markets charge for plastic bags.

5. **Seasonal Shopping:** Serbians prefer seasonal produce. Ask "Šta je sezonsko?" (What\'s in season?)

6. **Bargaining:** Light bargaining is sometimes acceptable at markets, especially for large quantities, but don\'t overdo it.

