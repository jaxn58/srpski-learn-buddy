## 4. Describing Sentences

### Basic Structure:

**Subject + verb "biti" + adjective**

Examples:
- **On je visok.** (He is tall.)
- **Ona je lepa.** (She is beautiful.)
- **Oni su pametni.** (They are smart.) - plural masculine
- **One su pametne.** (They are smart.) - plural feminine

### With "imati" (to have):

- **On ima plavu kosu.** (He has blonde hair.)
- **Ona ima zelene oči.** (She has green eyes.)
- **Oni imaju dugu kosu.** (They have long hair.)

---

## 5. Comparatives

To say someone is "more" or "-er" (taller, smarter), add **-iji/-ija/-ije**:

| Basic | Comparative | Example |
|-------|-------------|---------|
| visok (tall) | viši | **On je viši od mene.** (He is taller than me.) |
| pametan (smart) | pametniji | **Ona je pametnija.** (She is smarter.) |
| lep (beautiful) | lepši | **Ova je lepša.** (This one is more beautiful.) |

**Note:** Some adjectives have irregular comparatives - we\'ll cover these in detail in Unit 22.

